def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Ariaska V5 HTB Training Pipeline")
    parser.add_argument("--all", action="store_true", help="Full pipeline: gen-data → SFT → DPO → merge → GGUF → HF upload")
    parser.add_argument("--track-a", action="store_true", help="Train only: SFT → DPO → merge → GGUF")
    parser.add_argument("--gen-data", action="store_true", help="Generate training data only")
    parser.add_argument("--gpu", choices=list(GPU_PRESETS.keys()), default=DEFAULT_GPU,
                        help=f"GPU preset for batch sizes (default: {DEFAULT_GPU})")
    parser.add_argument("--sft-count", type=int, default=15000, help="Number of SFT examples")
    parser.add_argument("--dpo-count", type=int, default=2500, help="Number of DPO pairs")
    parser.add_argument("--cloud-enhance", action="store_true",
                        help="Use Groq/OpenRouter/Together 70B for expert reasoning (KD)")
    parser.add_argument("--cloud-enhance-count", type=int, default=10000,
                        help="Max examples to enhance with cloud LLM (default: 10000 = nearly all)")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--skip-dpo", action="store_true", help="Skip DPO stage (SFT only)")
    parser.add_argument("--hf-upload", action="store_true",
                        help="Upload FP16 + GGUF to HuggingFace after training")
    parser.add_argument("--hf-repo", default="zer0aria/ariaska-cybersec3",
                        help="HuggingFace repo ID for upload")
    args = parser.parse_args()

    gpu = GPU_PRESETS[args.gpu]
    start = time.time()

    log.info("=" * 70)
    log.info(f"Ariaska V5 Training Pipeline — {gpu.name}")
    log.info(f"  GPU preset: {args.gpu} | SFT bs={gpu.sft_batch_size}×{gpu.sft_grad_accum}")
    log.info(f"  DPO bs={gpu.dpo_batch_size}×{gpu.dpo_grad_accum} | Epochs: SFT={gpu.num_epochs} DPO={gpu.dpo_epochs}")
    if args.cloud_enhance:
        log.info(f"  Cloud KD: enhancing up to {args.cloud_enhance_count} examples with 70B teacher")
    log.info("=" * 70)

    # ── Stage 0: Generate training data ──────────────────────────────────────
    if args.gen_data or args.all:
        log.info("=" * 70)
        log.info("STAGE 0: GENERATING TRAINING DATA")
        log.info("=" * 70)
        generate_training_data(
            sft_count=args.sft_count,
            dpo_count=args.dpo_count,
            seed=args.seed,
            cloud_enhance=args.cloud_enhance,
            cloud_enhance_count=args.cloud_enhance_count,
        )

    if args.gen_data:
        log.info(f"[DONE] Data generation complete in {time.time() - start:.0f}s")
        return

    # ── Stage 1–3: Train + merge ─────────────────────────────────────────────
    if args.track_a or args.all:
        ensure_base_model()  # Pull from HF if not already on disk
        track_a_lora_sft(gpu)

        if not args.skip_dpo:
            track_a_dpo(gpu)

        track_a_merge_gguf()

    # ── Stage 4: Upload to HuggingFace ───────────────────────────────────────
    if args.hf_upload or args.all:
        upload_to_huggingface(repo_id=args.hf_repo)

    elapsed = time.time() - start
    log.info("=" * 70)
    log.info(f"ALL DONE — {elapsed / 3600:.1f} hours total")
    log.info("=" * 70)
    log.info("Next steps:")
    log.info(f"  1. Download from HuggingFace:")
    log.info(f"       huggingface-cli download {args.hf_repo} --local-dir ~/models/ariaska-cybersec3")
    log.info("  2. Create Modelfile and register in Ollama:")
    log.info("       ollama create ariaska-cybersec3 -f Modelfile_ariaska_cybersec3")
    log.info("  3. Update ARIASKA_FAST_MODEL and ARIASKA_MEDIUM_MODEL env vars")
    log.info("  4. Run RL retraining: python scripts/offline_distill.py")


if __name__ == "__main__":
    main()
