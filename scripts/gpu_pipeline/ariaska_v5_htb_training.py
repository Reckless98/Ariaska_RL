def track_a_lora_sft(gpu: GPUConfig) -> None:
    """Stage A1: LoRA SFT on ariaska-cybersec2 FP16 with HTB data."""
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import LoraConfig, get_peft_model
    from trl import SFTTrainer, SFTConfig

    log.info("=" * 70)
    log.info(f"TRACK A — Stage 1: LoRA SFT on ariaska-cybersec2 [{gpu.name}]")
    log.info(f"  bs={gpu.sft_batch_size}, grad_accum={gpu.sft_grad_accum}, epochs={gpu.num_epochs}")
    log.info("=" * 70)

    tokenizer = AutoTokenizer.from_pretrained(str(CYBERSEC2_FP16))
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        str(CYBERSEC2_FP16),
        torch_dtype=torch.bfloat16,
        device_map="auto",
        attn_implementation="sdpa",  # flash_attention_2 if available, sdpa fallback
    )

    lora_config = LoraConfig(
        r=64,
        lora_alpha=128,
        target_modules=ALL_LINEAR,
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM",
    )
    model = get_peft_model(model, lora_config)
    model.print_trainable_parameters()

    # Merge HTB data with existing schema data (2:1 ratio)
    from datasets import load_dataset, concatenate_datasets

    htb_ds = load_dataset("json", data_files=str(HTB_SFT_DATA), split="train")
    schema_ds = load_dataset("json", data_files=str(SCHEMA_DATA), split="train")
    schema_subset = schema_ds.shuffle(seed=42).select(range(min(1500, len(schema_ds))))
    combined = concatenate_datasets([htb_ds, schema_subset]).shuffle(seed=42)

    log.info(f"[DATA] Combined: {len(htb_ds)} HTB + {len(schema_subset)} schema = {len(combined)}")

    training_args = SFTConfig(
        output_dir=str(CYBERSEC3_LORA_OUT),
        num_train_epochs=gpu.num_epochs,
        per_device_train_batch_size=gpu.sft_batch_size,
        gradient_accumulation_steps=gpu.sft_grad_accum,
        learning_rate=2e-4,
        lr_scheduler_type="cosine",
        warmup_ratio=0.05,
        bf16=True,
        logging_steps=10,
        save_strategy="epoch",
        max_length=1024,
        dataset_text_field=None,  # Uses messages format
        neftune_noise_alpha=5.0,
        report_to="none",
    )

    trainer = SFTTrainer(
        model=model,
        args=training_args,
        train_dataset=combined,
        processing_class=tokenizer,
    )

    log.info("[TRAIN] Starting LoRA SFT...")
    trainer.train()
    trainer.save_model(str(CYBERSEC3_LORA_OUT))
    tokenizer.save_pretrained(str(CYBERSEC3_LORA_OUT))
    log.info(f"[DONE] LoRA SFT saved → {CYBERSEC3_LORA_OUT}")

    del model, trainer
    gc.collect()
    torch.cuda.empty_cache()


def track_a_dpo(gpu: GPUConfig) -> None:
    """Stage A2: DPO alignment on SFT checkpoint using expert vs novice pairs."""
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import LoraConfig
    from trl import DPOConfig, DPOTrainer

    log.info("=" * 70)
    log.info(f"TRACK A — Stage 2: DPO Alignment [{gpu.name}]")
    log.info(f"  bs={gpu.dpo_batch_size}, grad_accum={gpu.dpo_grad_accum}, epochs={gpu.dpo_epochs}")
    log.info("=" * 70)

    if not HTB_DPO_DATA.exists():
        log.warning(f"[SKIP] DPO data not found at {HTB_DPO_DATA} — skipping DPO stage")
        return

    from datasets import load_dataset
    dpo_ds = load_dataset("json", data_files=str(HTB_DPO_DATA), split="train")
    if len(dpo_ds) < 50:
        log.warning(f"[SKIP] Only {len(dpo_ds)} DPO examples — need at least 50, skipping")
        return

    log.info(f"[DATA] DPO dataset: {len(dpo_ds)} preference pairs")

    tokenizer = AutoTokenizer.from_pretrained(str(CYBERSEC3_LORA_OUT))
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        str(CYBERSEC3_LORA_OUT),
        torch_dtype=torch.bfloat16,
        device_map="auto",
        attn_implementation="sdpa",  # flash_attention_2 if available, sdpa fallback
    )

    # Lighter LoRA for DPO — smaller rank to avoid catastrophic forgetting
    lora_config = LoraConfig(
        r=32,
        lora_alpha=64,
        target_modules=ALL_LINEAR,
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM",
    )

    dpo_config = DPOConfig(
        output_dir=str(CYBERSEC3_DPO_OUT),
        num_train_epochs=gpu.dpo_epochs,
        per_device_train_batch_size=gpu.dpo_batch_size,
        gradient_accumulation_steps=gpu.dpo_grad_accum,
        learning_rate=5e-5,
        lr_scheduler_type="cosine",
        warmup_ratio=0.1,
        bf16=True,
        logging_steps=10,
        save_strategy="epoch",
        max_length=1024,
        beta=0.1,  # KL penalty — lower = more aggressive preference learning
        report_to="none",
    )

    trainer = DPOTrainer(
        model=model,
        args=dpo_config,
        train_dataset=dpo_ds,
        processing_class=tokenizer,
        peft_config=lora_config,
    )

    log.info("[TRAIN] Starting DPO alignment...")
    trainer.train()
    trainer.save_model(str(CYBERSEC3_DPO_OUT))
    tokenizer.save_pretrained(str(CYBERSEC3_DPO_OUT))
    log.info(f"[DONE] DPO model saved → {CYBERSEC3_DPO_OUT}")

    del model, trainer
    gc.collect()
    torch.cuda.empty_cache()


def track_a_merge_gguf() -> None:
    """Stage A3: Merge LoRA + quantize to GGUF.

    Picks the best checkpoint: DPO output if available, else SFT output.
    """
    from peft import AutoPeftModelForCausalLM
    from transformers import AutoTokenizer

    log.info("=" * 70)
    log.info("TRACK A — Stage 3: Merge LoRA → GGUF")
    log.info("=" * 70)

    # Use DPO checkpoint if it exists, otherwise fall back to SFT
    checkpoint_dir = CYBERSEC3_DPO_OUT if CYBERSEC3_DPO_OUT.exists() else CYBERSEC3_LORA_OUT
    log.info(f"[MERGE] Loading from: {checkpoint_dir}")

    model = AutoPeftModelForCausalLM.from_pretrained(
        str(checkpoint_dir),
        torch_dtype=torch.bfloat16,
        device_map="cpu",
    )
    merged = model.merge_and_unload()

    CYBERSEC3_MERGED.mkdir(parents=True, exist_ok=True)
    merged.save_pretrained(str(CYBERSEC3_MERGED))

    tokenizer = AutoTokenizer.from_pretrained(str(checkpoint_dir))
    tokenizer.save_pretrained(str(CYBERSEC3_MERGED))

    log.info(f"[MERGED] FP16 model → {CYBERSEC3_MERGED}")

    # Convert to GGUF
    CYBERSEC3_GGUF.mkdir(parents=True, exist_ok=True)

    for quant in ["Q8_0"]:
        out_file = CYBERSEC3_GGUF / f"ariaska-cybersec3-{quant.lower()}.gguf"
        cmd = [
            "python", "-m", "llama_cpp.convert",
            "--outfile", str(out_file),
            "--outtype", quant.lower().replace("_", "-"),
            str(CYBERSEC3_MERGED),
        ]
        log.info(f"[GGUF] Converting {quant}...")
        try:
            subprocess.run(cmd, check=True, capture_output=True)
            log.info(f"[GGUF] {quant} → {out_file}")
        except (subprocess.CalledProcessError, FileNotFoundError):
            # Fallback: try llama.cpp convert directly
            log.warning(f"[GGUF] llama_cpp.convert failed, trying llama-quantize...")
            try:
                # First convert to f16 gguf
                f16_gguf = CYBERSEC3_GGUF / "ariaska-cybersec3-f16.gguf"
                subprocess.run(
                    ["python", "/workspace/llama.cpp/convert_hf_to_gguf.py",
                     str(CYBERSEC3_MERGED), "--outfile", str(f16_gguf), "--outtype", "f16"],
                    check=True,
                )
                subprocess.run(
                    ["/workspace/llama.cpp/build/bin/llama-quantize",
                     str(f16_gguf), str(out_file), quant],
                    check=True,
                )
                log.info(f"[GGUF] {quant} → {out_file}")
            except Exception as e:
                log.error(f"[GGUF] Failed {quant}: {e}")

    del model, merged
    gc.collect()


def upload_to_huggingface(
    repo_id: str = "zer0aria/ariaska-cybersec3",
    upload_fp16: bool = True,
    upload_gguf: bool = True,
) -> None:
    """Upload merged FP16 and/or GGUF models to HuggingFace Hub.

    Much faster than scp from vast.ai — HF has high-bandwidth ingress.
    Download locally via: huggingface-cli download zer0aria/ariaska-cybersec3
    """
    log.info("=" * 70)
    log.info(f"UPLOADING TO HUGGINGFACE: {repo_id}")
    log.info("=" * 70)

    try:
        from huggingface_hub import HfApi, create_repo
    except ImportError:
        log.info("[HF] Installing huggingface_hub...")
        subprocess.run([sys.executable, "-m", "pip", "install", "huggingface_hub"], check=True)
        from huggingface_hub import HfApi, create_repo

    api = HfApi()

    # Create repo if it doesn't exist
    try:
        create_repo(repo_id, repo_type="model", exist_ok=True, private=True)
        log.info(f"[HF] Repository {repo_id} ready")
    except Exception as e:
        log.warning(f"[HF] Repo creation note: {e}")

    if upload_fp16 and CYBERSEC3_MERGED.exists():
        log.info(f"[HF] Uploading FP16 model from {CYBERSEC3_MERGED}...")
        api.upload_folder(
            folder_path=str(CYBERSEC3_MERGED),
            repo_id=repo_id,
            path_in_repo="fp16",
            commit_message="ariaska-cybersec3 FP16 merged model",
        )
        log.info("[HF] FP16 upload complete")

    if upload_gguf and CYBERSEC3_GGUF.exists():
        log.info(f"[HF] Uploading GGUF files from {CYBERSEC3_GGUF}...")
        api.upload_folder(
            folder_path=str(CYBERSEC3_GGUF),
            repo_id=repo_id,
            path_in_repo="gguf",
            commit_message="ariaska-cybersec3 GGUF quantizations",
        )
        log.info("[HF] GGUF upload complete")

    log.info(f"[HF] Done — download with: huggingface-cli download {repo_id}")


