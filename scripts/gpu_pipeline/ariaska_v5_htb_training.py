def generate_training_data(
    sft_count: int = 15000,
    dpo_count: int = 2500,
    output_parse_count: int = 2000,
    seed: int = 42,
    cloud_enhance: bool = False,
    cloud_enhance_count: int = 3000,
) -> Dict[str, Path]:
    """Generate all training data via generate_htb_data.py.

    Returns dict mapping data type to output file path.
    """
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    # Locate generator script (same directory as this file)
    gen_script = Path(__file__).parent / "generate_htb_data.py"
    if not gen_script.exists():
        raise FileNotFoundError(f"Generator not found: {gen_script}")

    cmd = [
        sys.executable, str(gen_script),
        "--output-dir", str(DATA_DIR),
        "--sft-count", str(sft_count),
        "--dpo-count", str(dpo_count),
        "--output-parse-count", str(output_parse_count),
        "--seed", str(seed),
    ]
    if cloud_enhance:
        cmd += ["--cloud-enhance", "--cloud-enhance-count", str(cloud_enhance_count)]

    log.info(f"[DATA] Running: {' '.join(cmd)}")
    datagen_log = DATA_DIR / "datagen_progress.log"
    log.info(f"[DATA] Progress log: {datagen_log}")
    with open(datagen_log, "w") as logf:
        result = subprocess.run(cmd, stdout=logf, stderr=subprocess.STDOUT, text=True)
    if result.returncode != 0:
        log.error(f"[DATA] Generator failed — see {datagen_log}")
        # Print last 50 lines for debugging
        try:
            lines = datagen_log.read_text().splitlines()
            log.error(f"[DATA] Last 50 lines:\n" + "\n".join(lines[-50:]))
        except Exception:
            pass
        raise RuntimeError(f"generate_htb_data.py failed (rc={result.returncode})")

    log.info(f"[DATA] Generator complete — see {datagen_log}")

    return {
        "sft": HTB_SFT_DATA,
        "dpo": HTB_DPO_DATA,
    }


def ensure_base_model() -> None:
    """Download base model from HuggingFace if not already present.

    Much faster than SCP from local — vast.ai ↔ HF has datacenter bandwidth.
    """
    config_file = CYBERSEC2_FP16 / "config.json"
    if config_file.exists():
        log.info(f"[BASE] Model already at {CYBERSEC2_FP16}")
        return

    log.info(f"[BASE] Downloading {HF_BASE_REPO}/fp16-merged from HuggingFace...")
    CYBERSEC2_FP16.mkdir(parents=True, exist_ok=True)

    try:
        from huggingface_hub import snapshot_download
        tmp_dir = snapshot_download(
            HF_BASE_REPO,
            allow_patterns=["fp16-merged/*"],
            local_dir=CYBERSEC2_FP16.parent / "_hf_tmp",
            local_dir_use_symlinks=False,
        )
        # Move files from fp16-merged/ subdirectory to the target
        src = Path(tmp_dir) / "fp16-merged"
        if src.exists():
            for f in src.iterdir():
                f.rename(CYBERSEC2_FP16 / f.name)
            (CYBERSEC2_FP16.parent / "_hf_tmp").exists() and None  # cleanup handled by snapshot_download
        log.info(f"[BASE] Downloaded to {CYBERSEC2_FP16}")
    except Exception as e:
        log.error(f"[BASE] HF download failed: {e}")
        log.error("[BASE] Ensure HF_TOKEN is set and has access to the repo")
        raise


