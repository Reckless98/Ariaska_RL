#!/usr/bin/env python3
"""
ariaska_v5_htb_training.py — Phase 57 HTB-Ready Training Pipeline

Optimized for RTX 5090 / 4080S (32GB VRAM), $10 budget @ $0.12-$0.17/hr.

Track A: LoRA SFT + DPO on ariaska-cybersec2 FP16 → ariaska-cybersec3 (4B)
  Stage 1: LoRA SFT (r=64) — HTB attack chains + schema compliance
  Stage 2: DPO alignment — expert vs novice judgment training
  Stage 3: Merge + GGUF quantize → ready for Ollama

Training data from generate_htb_data.py (93 attack chains, 27 real HTB/THM boxes).
Optional cloud-enhanced reasoning via Groq 70B (--cloud-enhance).

5090 settings: bs=4, grad_accum=4, epochs=3, seq_len=1024 → ~2h SFT + ~1h DPO
4080S settings: bs=2, grad_accum=8, epochs=3, seq_len=1024 → ~4h SFT + ~2h DPO

Usage:
  python ariaska_v5_htb_training.py --all                    # Full pipeline
  python ariaska_v5_htb_training.py --gen-data               # Data only
  python ariaska_v5_htb_training.py --gen-data --cloud-enhance  # Data with Groq 70B
  python ariaska_v5_htb_training.py --track-a                # SFT+DPO+merge
  python ariaska_v5_htb_training.py --gpu 5090               # 5090 batch settings
"""

